import { computeExecutionSchedule } from '../graph/execution-schedule.js';

const DESKTOP_SAMPLE_WIDTH_PX = 1200;
const UNBOUNDED_RANGE_THRESHOLD_PX = 9000;
const DEFAULT_RANGE_MAX_PX = 9999;
const SAMPLE_WIDTH_MIN_PX = 320;
const SAMPLE_WIDTH_MAX_PX = 1920;
const SAMPLE_RANGE_CAP_PX = 1600;

const EXPORT_CSS_HEADER = `/* ==========================================================================
   Generated by Kinetix Studio — Visual Responsive Animation Orchestrator
   Apply directly to your site by matching the IDs (#id) & classes (.class)
   defined in your Mock Screen.
   ========================================================================== */\n\n`;

export function generateProductionCSS(nodes) {
  const nodeList = nodes || [];
  return (
    EXPORT_CSS_HEADER +
    buildExportKeyframes(nodeList) +
    buildResponsiveSelectorCss(nodeList) +
    buildReducedMotionCss(nodeList)
  );
}

export function formatKeyframeDeclarations(keyframe) {
  const translateXPx = keyframe.translateX || 0;
  const translateYPx = keyframe.translateY || 0;
  const scale = keyframe.scale !== undefined ? keyframe.scale : 1;
  const rotateDeg = keyframe.rotate || 0;
  const opacity = keyframe.opacity !== undefined ? keyframe.opacity : 1;
  const blurPx = keyframe.blur || 0;

  const declarations = [
    `transform: translate3d(${translateXPx}px, ${translateYPx}px, 0) scale(${scale}) rotate(${rotateDeg}deg);`,
    `opacity: ${opacity};`,
    `filter: blur(${blurPx}px);`
  ];

  if (!keyframe.useColors) return declarations;
  return [...declarations, ...formatColorDeclarations(keyframe)];
}

function formatColorDeclarations(keyframe) {
  const declarations = [];
  if (keyframe.bgColor) declarations.push(`background-color: ${keyframe.bgColor};`);
  if (keyframe.textColor) declarations.push(`color: ${keyframe.textColor};`);
  if (keyframe.borderColor) declarations.push(`border-color: ${keyframe.borderColor};`);
  if (keyframe.borderRadius !== undefined && keyframe.borderRadius !== '') {
    declarations.push(`border-radius: ${keyframe.borderRadius}px;`);
  }
  return declarations;
}

export function sortKeyframesByOffset(keyframes) {
  return (keyframes || []).slice().sort((first, second) => first.offset - second.offset);
}

export function groupStepsByTarget(steps) {
  const stepsByTarget = {};
  steps.forEach((step) => {
    if (!stepsByTarget[step.target]) stepsByTarget[step.target] = [];
    stepsByTarget[step.target].push(step);
  });
  return stepsByTarget;
}

function formatAnimationDelay(step) {
  return step.staggerMs > 0
    ? `calc(${step.startMs}ms + (var(--stagger-index, 0) * ${step.staggerMs}ms))`
    : `${step.startMs}ms`;
}

export function formatAnimationShorthand(keyframesName, step) {
  return `${keyframesName} ${step.durationMs}ms ${step.easing} ${formatAnimationDelay(step)} both`;
}

function toExportKeyframesName(nodeId) {
  return `kx-${nodeId.replace(/[^a-zA-Z0-9-_]/g, '')}`;
}

function buildExportKeyframes(nodes) {
  return nodes
    .filter((node) => node.type === 'animation')
    .map((node) => {
      const stops = sortKeyframesByOffset(node.keyframes)
        .map((keyframe) => `  ${keyframe.offset}% {\n    ${formatKeyframeDeclarations(keyframe).join('\n    ')}\n  }`)
        .join('\n');
      return `@keyframes ${toExportKeyframesName(node.id)} {\n${stops}\n}\n\n`;
    })
    .join('');
}

function buildResponsiveSelectorCss(nodes) {
  const rangeRouterNode = nodes.find(
    (node) => node.type === 'condition' && node.conditionType === 'viewportRanges'
  );
  const hasWidthRanges =
    rangeRouterNode && Array.isArray(rangeRouterNode.ranges) && rangeRouterNode.ranges.length > 0;

  if (hasWidthRanges) {
    return rangeRouterNode.ranges.map((range) => buildWidthRangeCss(nodes, range)).join('');
  }

  const desktopSchedule = computeExecutionSchedule(nodes, {
    viewportWidth: DESKTOP_SAMPLE_WIDTH_PX,
    prefersReducedMotion: false
  });
  return `/* --- Primary Animation Sequence --- */\n` + buildExportSelectorRules(desktopSchedule.steps, '');
}

function buildWidthRangeCss(nodes, range) {
  const rangeSchedule = computeExecutionSchedule(nodes, {
    viewportWidth: getRangeSampleWidth(range),
    prefersReducedMotion: false
  });
  if (rangeSchedule.steps.length === 0) return '';

  const heading = `/* --- Width Range Branch: ${range.label} --- */\n`;
  const mediaQuery = buildRangeMediaQuery(range);
  if (!mediaQuery) return heading + buildExportSelectorRules(rangeSchedule.steps, '');
  return `${heading}${mediaQuery} {\n${buildExportSelectorRules(rangeSchedule.steps, '  ')}}\n\n`;
}

function getRangeSampleWidth(range) {
  const midpointPx = Math.floor((Number(range.min) + Math.min(Number(range.max), SAMPLE_RANGE_CAP_PX)) / 2);
  return Math.min(SAMPLE_WIDTH_MAX_PX, Math.max(SAMPLE_WIDTH_MIN_PX, midpointPx));
}

function buildRangeMediaQuery(range) {
  const minWidthPx = Number(range.min) || 0;
  const maxWidthPx = Number(range.max) || DEFAULT_RANGE_MAX_PX;
  const hasMinBound = minWidthPx > 0;
  const hasMaxBound = maxWidthPx < UNBOUNDED_RANGE_THRESHOLD_PX;

  if (!hasMinBound && hasMaxBound) return `@media (max-width: ${maxWidthPx}px)`;
  if (hasMinBound && !hasMaxBound) return `@media (min-width: ${minWidthPx}px)`;
  if (hasMinBound && hasMaxBound) return `@media (min-width: ${minWidthPx}px) and (max-width: ${maxWidthPx}px)`;
  return '';
}

function buildReducedMotionCss(nodes) {
  const hasReducedMotionGuard = nodes.some(
    (node) => node.type === 'condition' && node.conditionType === 'reducedMotion'
  );
  if (!hasReducedMotionGuard) return '';

  const reducedMotionSchedule = computeExecutionSchedule(nodes, {
    viewportWidth: DESKTOP_SAMPLE_WIDTH_PX,
    prefersReducedMotion: true
  });
  return (
    `/* --- Accessibility Guard: Prefers Reduced Motion --- */\n` +
    `@media (prefers-reduced-motion: reduce) {\n` +
    buildExportSelectorRules(reducedMotionSchedule.steps, '  ') +
    `}\n`
  );
}

function buildExportSelectorRules(steps, indent) {
  return Object.entries(groupStepsByTarget(steps))
    .map(([selector, targetSteps]) => {
      const animations = targetSteps.map((step) => formatAnimationShorthand(toExportKeyframesName(step.nodeId), step));
      const firstStep = targetSteps[0];
      let rule = `${indent}${selector} {\n`;
      rule += `${indent}  will-change: transform, opacity, filter, background-color, color;\n`;
      rule += `${indent}  animation: ${animations.join(',\n             ')};\n`;
      if (firstStep.cssMode === 'transition') {
        rule += `${indent}  ${formatTransitionDeclaration(firstStep)}\n`;
      }
      rule += `${indent}}\n\n`;
      return rule;
    })
    .join('');
}

function formatTransitionDeclaration(step) {
  const timing = `${step.durationMs}ms ${step.easing}`;
  return `transition: transform ${timing}, opacity ${timing}, background-color ${timing}, color ${timing}, border-color ${timing};`;
}
