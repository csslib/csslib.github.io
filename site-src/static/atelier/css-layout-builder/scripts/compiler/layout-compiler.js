import { declarationsForContainer, declarationsForItemInParent, declarationsForLeaf } from './layout-declarations.js';
import { COMPILER_FALLBACKS } from '../config/constants.js';
import { isConcreteLeaf } from '../tree/layout-tree.js';
import { indentEachLine } from '../utils/text-helpers.js';

const DEFAULT_SCOPE_SELECTOR = '.if-scope';
const BENTO_COLLAPSE_WIDTH_MULTIPLIER = 2.2;
const HTML_INDENT = '  ';
const CSS_DECLARATION_INDENT = '  ';
const EXPORT_STYLE_INDENT = '    ';
const EXPORT_BODY_INDENT = '  ';

const EXPORT_CSS_HEADER = `/* =========================================================
 * Generated by IntrinsicFlow — Zero/Minimal Media Query CSS
 * Uses intrinsic sizing: minmax(), min(), clamp(), flex-wrap
 * thresholds, position: sticky chrome, and @container.
 * ========================================================= */
*, *::before, *::after {
  box-sizing: border-box;
}`;

export function compileLayout(rootNode, scopeSelector = DEFAULT_SCOPE_SELECTOR) {
  const { cssRules, containerRules } = compileNodeRules(rootNode, { parentNode: null, childIndex: 0, scopeSelector });
  return {
    css: [EXPORT_CSS_HEADER, ...cssRules, ...containerRules].join('\n\n'),
    html: compileHtml(rootNode, 0)
  };
}

function compileHtml(node, depth = 0) {
  const indent = HTML_INDENT.repeat(depth);
  const tag = node.tag || 'div';
  const className = node.className || node.id;

  if (isConcreteLeaf(tag)) {
    const hrefAttribute = tag === 'a' ? ' href="#"' : '';
    return `${indent}<${tag} class="${className}"${hrefAttribute}>${node.text || ''}</${tag}>`;
  }

  const childMarkup = (node.children || [])
    .map(child => compileHtml(child, depth + 1))
    .join('\n');

  if (!childMarkup) {
    return `${indent}<${tag} class="${className}"></${tag}>`;
  }

  return `${indent}<${tag} class="${className}">\n${childMarkup}\n${indent}</${tag}>`;
}

export function buildSingleFileDocument(compiled) {
  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <title>Intrinsic Layout Structure</title>
  <style>
body {
  margin: 0;
  background: #f8fafc;
  color: #0f172a;
  font-family: system-ui, -apple-system, sans-serif;
}
${indentEachLine(compiled.css, EXPORT_STYLE_INDENT)}
  </style>
</head>
<body>
${indentEachLine(compiled.html, EXPORT_BODY_INDENT)}
</body>
</html>`;
}

function compileNodeRules(node, { parentNode, childIndex, scopeSelector }) {
  const selector = selectorForNode(node, scopeSelector);
  const isLeaf = isConcreteLeaf(node.tag);
  const declarations = [
    ...declarationsForItemInParent(node, parentNode, childIndex),
    ...(isLeaf ? declarationsForLeaf(node) : declarationsForContainer(node))
  ];
  const ownContainerRules = !isLeaf && node.behavior === 'bento-12'
    ? [compileBentoCollapseRule(node, selector)]
    : [];
  const childResults = !isLeaf && Array.isArray(node.children)
    ? node.children.map((child, index) => compileNodeRules(child, { parentNode: node, childIndex: index, scopeSelector }))
    : [];

  return {
    cssRules: [formatCssRule(selector, declarations), ...childResults.flatMap(result => result.cssRules)],
    containerRules: [...ownContainerRules, ...childResults.flatMap(result => result.containerRules)]
  };
}

function selectorForNode(node, scopeSelector) {
  return scopeSelector
    ? `${scopeSelector} [data-node-id="${node.id}"]`
    : `.${node.className || node.id}`;
}

function formatCssRule(selector, declarations) {
  const body = declarations.map(declaration => `${CSS_DECLARATION_INDENT}${declaration}`).join('\n');
  return `${selector} {\n${body}\n}`;
}

function compileBentoCollapseRule(node, selector) {
  const collapseWidthPx = Math.round((node.bentoCollapseWidth || COMPILER_FALLBACKS.bentoCollapseWidthPx) * BENTO_COLLAPSE_WIDTH_MULTIPLIER);
  return `@container (max-width: ${collapseWidthPx}px) {
  ${selector} > * {
grid-column: 1 / -1 !important;
  }
}`;
}

export function isSidebarChild(parentNode, childIndex) {
  const sidebarIndex = parentNode.sidebarSide === 'right' ? 1 : 0;
  return childIndex === sidebarIndex;
}
